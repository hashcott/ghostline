#!/bin/bash
# Installs, connects (best effort: needs the internet), removes and purges
# Ghostline on a CI runner, then checks the machine is as before.
# Usage: smoke.sh deb|tarball   (from the repo root, after linux:package)
set -euo pipefail
kind=${1:?usage: smoke.sh deb|tarball}
step() { echo "::group::$*"; }
end() { echo "::endgroup::"; }
die() { echo "FAIL: $*" >&2; exit 1; }

wait_socket() {
	for _ in $(seq 50); do [ -S /run/ghostline/ctl.sock ] && return 0; sleep 0.2; done
	die "no /run/ghostline/ctl.sock after 10 s"
}

connect() { # connect <ghostlined>: best effort, the runner's network decides
	if timeout 180 sudo "$1" connect; then
		echo "connected"
		sudo "$1" status
	else
		echo "::warning::connect failed on this runner; removal is still checked"
	fi
}

clean() { # the system is as before Ghostline
	! systemctl is-active --quiet ghostline || die "ghostline.service still active"
	! ls /run/systemd/resolved.conf.d/ 2>/dev/null | grep -qi ghostline || die "resolved drop-in left"
	! sudo nft list table inet ghostline >/dev/null 2>&1 || die "nftables table inet ghostline left"
	for d in /usr/local/share/ca-certificates /etc/pki/ca-trust/source/anchors /etc/ca-certificates/trust-source/anchors; do
		! ls "$d" 2>/dev/null | grep -qi ghostline || die "Ghostline CA left in $d"
	done
	if command -v ufw >/dev/null; then
		! sudo ufw status | grep -qi ghostline || die "ufw rule left"
	fi
	! grep -q 'Generated by Ghostline' /etc/resolv.conf 2>/dev/null || die "resolv.conf still Ghostline's"
	echo "clean"
}

purged() {
	[ ! -e /var/lib/ghostline ] || die "/var/lib/ghostline left"
	[ ! -e /var/log/ghostline ] || die "/var/log/ghostline left"
	echo "purged"
}

case "$kind" in
deb)
	step "install deb"
	sudo apt-get install -y ./bin/ghostline_*_amd64.deb
	systemctl is-active --quiet ghostline || die "service not active after install"
	wait_socket
	sudo /usr/lib/ghostline/ghostlined status
	end
	step "connect"; connect /usr/lib/ghostline/ghostlined; end
	step "remove"
	sudo apt-get remove -y ghostline
	clean
	[ -d /var/lib/ghostline ] || die "remove (not purge) dropped /var/lib/ghostline"
	end
	step "purge"; sudo apt-get purge -y ghostline; purged; end
	;;
tarball)
	tmp=$(mktemp -d)
	tar -C "$tmp" -xzf bin/ghostline-*-linux-amd64.tar.gz
	dir=$(echo "$tmp"/ghostline-*-linux-amd64)
	step "install.sh"
	sudo "$dir/install.sh"
	systemctl is-active --quiet ghostline || die "service not active after install.sh"
	wait_socket
	sudo /var/lib/ghostline/bin/ghostlined status
	end
	step "connect"; connect /var/lib/ghostline/bin/ghostlined; end
	step "uninstall.sh --purge"
	sudo "$dir/uninstall.sh" --purge
	clean
	[ ! -e /etc/systemd/system/ghostline.service ] || die "unit left"
	[ ! -e /usr/local/bin/ghostline ] || die "/usr/local/bin/ghostline left"
	purged
	end
	rm -rf "$tmp"
	;;
*) die "unknown kind $kind" ;;
esac
